vector<int> divs (int n)
{
	vi ret;
	for (int i = 1; i*i <= n; i++)
	{
		if (n % i == 0)
		{
			ret.pb(i);
			if (i * i != n) ret.pb(n / i);
		}
	}

	sort(all(ret));
	return ret;
}


void solve() {
	int n; cin >> n;
	vi divsN = divs(n);

	// a = n
	int ans = 1;

	// a + ar = n;
	ans += divsN.size() - 1;
	ans -= (n % 2) == 0;

	for (int &a: divsN)
	{
		for (int r = 2; r * r <= n; r++)
		{
			int cur = a + a * r;
			if (cur > n) break;

			int potenciaR = a * r;
			for (int m = 2; m < 31; m++)
			{
				potenciaR *= r;
				cur += potenciaR;

				if (cur == n) ans++;
				if (cur >= n) break;
			}
		}
	}

	cout << ans << endl;



}

